def quality_check(prompts: list) -> dict:
    """质量控制：去重、完整性检查、价值评分"""
    if not prompts:
        return {"pass": False, "error": "空列表"}
    
    issues = []
    
    # 1. 检查重复（按 prompt 字段去重）
    seen = set()
    duplicates = 0
    for p in prompts:
        key = p.get("prompt", "")[:50]  # 前50字符作为去重键
        if key in seen:
            duplicates += 1
        seen.add(key)
    if duplicates > 0:
        issues.append(f"发现 {duplicates} 条重复")
    
    # 2. 检查完整性（必须有 tag + prompt + usage）
    missing = sum(1 for p in prompts if not p.get("prompt") or not p.get("usage"))
    if missing > 0:
        issues.append(f"有 {missing} 条缺少必要字段")
    
    # 3. 检查内容长度（prompt 太短 = 没价值）
    too_short = sum(1 for p in prompts if len(p.get("prompt", "")) < 15)
    if too_short > 0:
        issues.append(f"有 {too_short} 条内容过短")
    
    # 4. 检查是否省略号占位
    placeholders = sum(1 for p in prompts if "……" in p.get("prompt", "") or "..." in p.get("prompt", ""))
    if placeholders > 0:
        issues.append(f"有 {placeholders} 条包含省略号占位")
    
    # 5. 质量评分
    total = len(prompts)
    unique_rate = (total - duplicates) / total
    completeness = (total - missing) / total
    quality_score = round(unique_rate * completeness * 100, 1)
    
    return {
        "pass": len(issues) == 0,
        "total": total,
        "duplicates": duplicates,
        "unique_rate": f"{unique_rate*100:.1f}%",
        "completeness": f"{completeness*100:.1f}%",
        "quality_score": quality_score,
        "issues": issues,
    }


def dedup_prompts(prompts: list) -> list:
    """去重"""
    seen = set()
    result = []
    for p in prompts:
        key = p.get("prompt", "")[:50]
        if key not in seen:
            seen.add(key)
            result.append(p)
    return result


def generate_txt_product(catalog_product: dict, out_dir: Path = None) -> Path:
    """生成完整 TXT 产品文件（可直接交付给客户）"""
    if out_dir is None:
        out_dir = PRODUCT_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    
    prompts = dedup_prompts(catalog_product["prompts"])
    qc = quality_check(prompts)
    
    lines = []
    lines.append("=" * 60)
    lines.append(f"📦 {catalog_product['name']}")
    lines.append(f"📋 共 {len(prompts)} 条提示词")
    lines.append(f"🏷️ 分类：{catalog_product['category']}")
    lines.append(f"📱 适合平台：{catalog_product['platforms']}")
    lines.append(f"✨ 质量评分：{qc['quality_score']} / 100")
    lines.append(f"🎁 使用说明：复制 Prompt 里的内容，粘贴到 AI 工具（文心一言/通义/豆包/Claude/GPT）里，把「{{占位符}}」替换成你的具体内容")
    lines.append("=" * 60)
    lines.append("")
    
    # 按 tag 分组
    from collections import OrderedDict
    grouped = OrderedDict()
    for p in prompts:
        tag = p.get("tag", "其他")
        if tag not in grouped:
            grouped[tag] = []
        grouped[tag].append(p)
    
    idx = 0
    for tag, items in grouped.items():
        lines.append(f"\n{'─' * 40}")
        lines.append(f"🔖 第 {idx+1} 组：{tag}（{len(items)} 条）")
        lines.append(f"{'─' * 40}\n")
        
        for i, item in enumerate(items):
            idx += 1
            lines.append(f"【{idx}】{item.get('prompt', '')}")
            if item.get("usage"):
                lines.append(f"   💡 使用：{item['usage']}")
            if item.get("example"):
                lines.append(f"   🌟 示例：{item['example']}")
            lines.append("")
    
    lines.append(f"\n{'=' * 60}")
    lines.append("🎁 感谢购买！祝赚钱多多！")
    lines.append("💬 有问题随时联系客服")
    lines.append("=" * 60)
    
    safe_id = catalog_product["product_id"].replace("/", "_")
    filepath = out_dir / f"{safe_id}_{catalog_product['name']}.txt"
    filepath.write_text("\n".join(lines), encoding="utf-8")
    
    return filepath


